/**
 * Liest die Translator-Konfiguration (aktuell: DeepL API-Key).
 *
 * WICHTIG (Beitrag: kritischer Bugfix nach gemeldetem Verschwinden des
 * gespeicherten API-Keys nach einem Addon-Update): die Config-Datei liegt
 * NICHT mehr innerhalb des Addon-Ordners selbst (vorher: addon/translator/
 * .config.php), sondern in einem eigenen, UPDATE-SICHEREN Verzeichnis
 * außerhalb von addon/ (analog zum bereits bestehenden _addon_backups-
 * Verzeichnis-Muster, siehe src/Addon/AddonManager.php). Grund: ein
 * Addon-Update tauscht das komplette Addon-Verzeichnis atomar aus
 * (atomicReplaceAddonDir()) - jede Datei, die NUR im alten Verzeichnis lag
 * und nicht Teil des neuen ZIP-Inhalts ist (wie eine zur Laufzeit
 * generierte Config-Datei), ging dadurch bei JEDEM Update verloren. Der
 * Browser zeigte durch Passwort-Feld-Autofill weiterhin Punkte im
 * Eingabefeld an, obwohl der Server den Key längst nicht mehr kannte -
 * das machte das Problem zusätzlich schwer bemerkbar.
 *
 * @return array{deepl_key: string}
 */
function translatorConfigDir(): string
{
    // __DIR__ = addon/translator/, zwei Ebenen hoch = Projekt-Root (siehe
    // dasselbe Muster in addon/pdf-export/PdfExporter.php für den
    // Hintergrund zur Verzeichnistiefe).
    return dirname(__DIR__, 2) . '/_addon_data/translator';
}

function translatorGetConfig(): array
{
    $dir  = translatorConfigDir();
    $path = $dir . '/config.php';

    // Migration von der alten (unsicheren) Position: existiert dort noch
    // eine Config-Datei (von vor diesem Fix), einmalig an den neuen,
    // update-sicheren Ort übernehmen, damit ein bereits gespeicherter
    // Key nicht zusätzlich durch DIESES Update verloren geht.
    $legacyPath = __DIR__ . '/.config.php';
    if (!is_file($path) && is_file($legacyPath)) {
        $legacyData = @include $legacyPath;
        if (is_array($legacyData)) {
            translatorSaveConfig($legacyData);
        }
    }

    if (is_file($path)) {
        $data = @include $path;
        if (is_array($data)) {
            return $data;
        }
    }
    return ['deepl_key' => ''];
}

/**
 * Speichert die Translator-Konfiguration.
 */
function translatorSaveConfig(array $config): void
{
    $dir = translatorConfigDir();
    if (!is_dir($dir)) {
        @mkdir($dir, 0755, true);
        // Sicherheitshinweis wie bei _addon_backups: Verzeichnis vor
        // direktem Web-Zugriff sperren, falls der Server .htaccess
        // auswertet (Apache) - enthält perspektivisch sensible Werte wie
        // den DeepL API-Key.
        @file_put_contents($dir . '/.htaccess', "Deny from all\nRequire all denied\n");
    }
    $content = "<?php\n// Auto-generated by translator addon.\nreturn "
        . var_export($config, true) . ";\n";
    file_put_contents($dir . '/config.php', $content);
}

/**
 * Erlaubte Sprach-Codes (2-stellig, lowercase, alphanumerisch).
 */
function translatorValidLangCode(string $code): bool
{
    return (bool) preg_match('/^[a-z]{2,3}$/', $code);
}

/**
 * Scannt alle Sprachverzeichnisse (Core + Addons) und listet verfügbare
 * Sprachdateien auf. Erkennt beliebig viele Sprachen pro Verzeichnis.
 *
 * @return array<string, array{label: string, group: string, dir: string, languages: array<int,string>}>
 */
function translatorScanLangFiles(): array
{
    $base  = dirname(__DIR__, 2);
    $found = [];

    // Core lang/ Verzeichnisse (lang/admin/, lang/frontend/, ...)
    $coreLangDir = $base . '/lang/';
    if (is_dir($coreLangDir)) {
        foreach (scandir($coreLangDir) as $dir) {
            if ($dir === '.' || $dir === '..') {
                continue;
            }
            $langDir = $coreLangDir . $dir . '/';
            $languages = translatorDiscoverLanguages($langDir);
            if (!empty($languages)) {
                $key = 'core:' . $dir;
                $found[$key] = [
                    'label'     => 'Core: ' . ucfirst($dir),
                    'group'     => 'core',
                    'dir'       => $langDir,
                    'languages' => $languages,
                ];
            }
        }
    }

    // Addon lang/ Verzeichnisse (addon/*/lang/)
    $addonDir = $base . '/addon/';
    if (is_dir($addonDir)) {
        foreach (scandir($addonDir) as $dir) {
            if ($dir === '.' || $dir === '..') {
                continue;
            }
            $langDir = $addonDir . $dir . '/lang/';
            $languages = translatorDiscoverLanguages($langDir);
            if (!empty($languages)) {
                $key = 'addon:' . $dir;
                $found[$key] = [
                    'label'     => 'Addon: ' . $dir,
                    'group'     => 'addon',
                    'dir'       => $langDir,
                    'languages' => $languages,
                ];
            }
        }
    }

    // Core zuerst, dann Addons alphabetisch
    uksort($found, static function ($a, $b) use ($found) {
        $ga = $found[$a]['group'];
        $gb = $found[$b]['group'];
        if ($ga !== $gb) {
            return $ga === 'core' ? -1 : 1;
        }
        return strcasecmp($a, $b);
    });

    return $found;
}

/**
 * Findet alle Sprachdateien (*.php) in einem Verzeichnis und gibt die
 * Sprach-Codes zurück (z.B. ['de', 'en', 'fr']).
 *
 * @return array<int,string>
 */
function translatorDiscoverLanguages(string $dir): array
{
    if (!is_dir($dir)) {
        return [];
    }
    $langs = [];
    foreach (scandir($dir) as $file) {
        if (preg_match('/^([a-z]{2,3})\.php$/', $file, $m)) {
            $langs[] = $m[1];
        }
    }
    sort($langs);
    return $langs;
}

/**
 * Baut den Dateipfad für eine Sprache in einem Verzeichnis.
 *
 * SICHERHEIT (Path-Traversal-Fix): validiert $lang jetzt IMMER gegen
 * translatorValidLangCode() (nur 2-3 Kleinbuchstaben) - vorher wurde diese
 * Prüfung nur beim Anlegen einer NEUEN Sprache aufgerufen, nicht beim
 * Speichern/Anzeigen einer bereits bestehenden. $srcLang/$tgtLang kommen
 * aber direkt aus $_POST bzw. $_GET (view_translator.php) - ohne diese
 * Prüfung hätte z.B. tgt_lang=../../../../config einen Pfad weit außerhalb
 * des vorgesehenen Sprachordners ergeben (Path Traversal, beim Schreiben
 * potenziell beliebige .php-Dateien im Dateisystem erzeugend, beim Lesen
 * eine Local File Inclusion - view_translator.php lädt die Datei per
 * require, nicht nur lesend).
 *
 * Validierung an EINER zentralen Stelle statt bei jedem Aufrufer einzeln
 * - so ist es strukturell nicht mehr möglich, diese Prüfung versehentlich
 * an einer neuen Aufrufstelle zu vergessen. Zusätzlich realpath()-
 * Gegenprobe (Verteidigung in der Tiefe, siehe src/Addon/AddonManager.php
 * für dasselbe Muster bei der Addon-Installation): der aufgelöste Pfad
 * MUSS exakt innerhalb von $dir liegen.
 *
 * @return string|null Der Pfad, oder null bei ungültigem/unsicherem $lang.
 */
function translatorLangFilePath(string $dir, string $lang): ?string
{
    if (!translatorValidLangCode($lang)) {
        return null;
    }

    $path = $dir . $lang . '.php';

    $realDir = realpath($dir);
    if ($realDir === false) {
        return null;
    }
    // Bei einer NEUEN Sprachdatei existiert $path selbst noch nicht -
    // realpath($path) wäre dann false. Deshalb wird stattdessen das
    // ELTERNVERZEICHNIS des Zielpfads geprüft (= $dir, aber realpath-
    // aufgelöst, falls $dir z.B. über einen Symlink erreicht wurde).
    $realParent = realpath(dirname($path));
    if ($realParent === false || $realParent !== $realDir) {
        return null;
    }

    return $path;
}

/**
 * Lädt eine PHP-Sprachdatei und gibt das Array zurück.
 */
function translatorLoadLangFile(string $path): array
{
    if (!is_file($path)) {
        return [];
    }
    // isoliert ausführen, um Namenskollisionen zu vermeiden
    $data = (static function () use ($path) {
        return @require $path;
    })();
    return is_array($data) ? $data : [];
}

/**
 * Speichert ein Array als PHP-Sprachdatei. Vorhandene Datei-Header
 * (PHPDoc-Kommentare vor `return [`) bleiben erhalten. Erstellt die Datei
 * neu, falls sie noch nicht existiert.
 */
/**
 * Speichert eine Sprachdatei.
 *
 * SICHERHEITSNETZ (Beitrag: Bugfix nach gemeldetem Datenverlust - siehe
 * view_translator.php für den eigentlichen Auslöser): verweigert das
 * Schreiben, wenn der neue Datensatz DRASTISCH weniger befüllte Werte hat
 * als der bereits vorhandene (z.B. eine bestehende Datei mit 711 echten
 * Texten würde durch einen fehlerhaften Aufruf mit fast nur leeren Werten
 * ersetzt). Das ist eine allgemeine, vom genauen Auslöser UNABHÄNGIGE
 * Bremse - schützt auch vor noch unbekannten, zukünftigen Bugs mit
 * ähnlicher Wirkung, nicht nur vor dem einen konkret behobenen. Schwelle
 * bewusst konservativ gewählt (nur bei einem drastischen Rückgang auf
 * unter 20% der vorherigen befüllten Werte), damit legitimes, gewolltes
 * Leeren einzelner/weniger Einträge nicht blockiert wird.
 *
 * @return bool true = gespeichert, false = verweigert (Verdacht auf Datenverlust)
 */
function translatorSaveLangFile(string $path, array $data): bool
{
    if (is_file($path)) {
        $existing = translatorLoadLangFile($path);
        $existingFilled = 0;
        foreach ($existing as $v) {
            if ($v !== '') { $existingFilled++; }
        }
        if ($existingFilled >= 10) {
            $newFilled = 0;
            foreach ($data as $v) {
                if ($v !== '') { $newFilled++; }
            }
            if ($newFilled < $existingFilled * 0.2) {
                error_log(sprintf(
                    '[translator] Speichern von %s abgelehnt: nur %d von zuvor %d befüllten Werten '
                    . '(Verdacht auf versehentlichen Datenverlust).',
                    $path,
                    $newFilled,
                    $existingFilled
                ));
                return false;
            }
        }
    }

    // Header bewahren (alles vor `return [`)
    $header = "<?php\n";
    if (is_file($path)) {
        $raw    = file_get_contents($path);
        $pos    = strpos($raw, 'return [');
        if ($pos !== false) {
            $header = substr($raw, 0, $pos);
            $header = rtrim($header) . "\n\n";
        }
    }

    // Body generieren
    $body = "return [\n";
    foreach ($data as $key => $value) {
        $escKey   = str_replace(["\\", "'"], ["\\\\", "\\'"], (string)$key);
        $escValue = str_replace(["\\", "'"], ["\\\\", "\\'"], (string)$value);
        $body .= "    '{$escKey}' => '{$escValue}',\n";
    }
    $body .= "];\n";

    file_put_contents($path, $header . $body);
    return true;
}

/**
 * Übersetzt einen Batch von Texten via DeepL API.
 *
 * @param array<int,string> $texts   Zu übersetzende Texte
 * @param string            $source  Quellsprache ('de')
 * @param string            $target  Zielsprache ('en', 'fr', 'es', ...)
 * @param string            $apiKey  DeepL API-Key
 * @return array<int,string> Übersetzte Texte (gleiche Reihenfolge), oder [] bei Fehler
 */
/**
 * Übersetzt einen Batch von Texten via DeepL API.
 *
 * ROBUSTHEIT (Beitrag: Bugfix nach gemeldetem "Auto-Übersetzen tut nichts,
 * keine erkennbare Fehlermeldung"): liefert jetzt eine STRUKTURIERTE
 * Antwort mit konkretem Fehlergrund + HTTP-Status statt nur eines leeren
 * Arrays - der Aufrufer (case 'auto_translate') kann dem Nutzer dadurch
 * sagen, WARUM es fehlgeschlagen ist (z.B. ungültiger API-Key, falsche
 * Domain/URL, Netzwerkfehler), statt "es passiert einfach nichts"
 * anzuzeigen. curl wird jetzt VOR file_get_contents versucht (nicht mehr
 * als Fallback danach) - curl liefert zuverlässig den HTTP-Statuscode auch
 * bei Fehlern, file_get_contents ohne besondere Konfiguration meist nur
 * "false" ohne jedes Detail.
 *
 * @param array<int,string> $texts   Zu übersetzende Texte
 * @param string            $source  Quellsprache ('de')
 * @param string            $target  Zielsprache ('en', 'fr', 'es', ...)
 * @param string            $apiKey  DeepL API-Key
 * @return array{success:bool,translations:array<int,string>,error:string,http_code:int}
 */
function translatorDeepLTranslate(array $texts, string $source, string $target, string $apiKey): array
{
    if ($apiKey === '') {
        return ['success' => false, 'translations' => [], 'error' => 'kein API-Key hinterlegt', 'http_code' => 0];
    }
    if (empty($texts)) {
        return ['success' => true, 'translations' => [], 'error' => '', 'http_code' => 0];
    }

    $isFree = str_ends_with($apiKey, ':fx');
    $url = $isFree
        ? 'https://api-free.deepl.com/v2/translate'
        : 'https://api.deepl.com/v2/translate';

    // POST-Body manuell bauen (DeepL erwartet mehrere text= Parameter).
    // BUGFIX (gemeldet: "HTTP 403: Missing Authorization header, expected
    // 'Authorization: DeepL-Auth-Key <API key>'"): DeepL verlangt den
    // API-Key inzwischen als eigenen HTTP-Header, nicht mehr (nur) als
    // auth_key-Feld im POST-Body - der Body enthält den Key deshalb nicht
    // mehr, stattdessen wird unten bei BEIDEN Übertragungswegen (curl UND
    // file_get_contents-Fallback) ein "Authorization: DeepL-Auth-Key ..."-
    // Header gesetzt.
    $postData = 'source_lang=' . strtoupper(substr($source, 0, 2));
    $postData .= '&target_lang=' . strtoupper(substr($target, 0, 2));
    foreach ($texts as $text) {
        $postData .= '&text=' . urlencode($text);
    }

    $authHeader = 'Authorization: DeepL-Auth-Key ' . $apiKey;

    $response = false;
    $httpCode = 0;

    if (function_exists('curl_init')) {
        $ch = curl_init($url);
        curl_setopt($ch, CURLOPT_POST, true);
        curl_setopt($ch, CURLOPT_POSTFIELDS, $postData);
        curl_setopt($ch, CURLOPT_RETURNTRANSFER, true);
        curl_setopt($ch, CURLOPT_HTTPHEADER, [
            'Content-Type: application/x-www-form-urlencoded',
            $authHeader,
        ]);
        curl_setopt($ch, CURLOPT_TIMEOUT, 30);
        $response  = curl_exec($ch);
        $httpCode  = (int)curl_getinfo($ch, CURLINFO_HTTP_CODE);
        $curlError = curl_error($ch);
        curl_close($ch);
        if ($response === false) {
            return ['success' => false, 'translations' => [], 'error' => 'Verbindung fehlgeschlagen: ' . $curlError, 'http_code' => 0];
        }
    } else {
        // Fallback nur, wenn curl auf diesem Server nicht verfügbar ist.
        // ignore_errors=true, damit auch bei einem Nicht-2xx-Status der
        // eigentliche Antwort-Body (mit der DeepL-Fehlermeldung) gelesen
        // wird, statt dass file_get_contents nur "false" zurückgibt.
        $opts = [
            'http' => [
                'method'        => 'POST',
                'header'        => "Content-Type: application/x-www-form-urlencoded\r\n"
                                    . $authHeader . "\r\n",
                'content'       => $postData,
                'timeout'       => 30,
                'ignore_errors' => true,
            ],
        ];
        $context  = stream_context_create($opts);
        $response = @file_get_contents($url, false, $context);
        if (isset($http_response_header[0]) && preg_match('#HTTP/\S+\s+(\d+)#', $http_response_header[0], $m)) {
            $httpCode = (int)$m[1];
        }
        if ($response === false) {
            return ['success' => false, 'translations' => [], 'error' => 'Verbindung fehlgeschlagen (keine curl-Erweiterung verfügbar)', 'http_code' => 0];
        }
    }

    $decoded = json_decode($response, true);

    if ($httpCode !== 200) {
        $apiMessage = is_array($decoded) && isset($decoded['message']) ? (string)$decoded['message'] : substr($response, 0, 200);
        return ['success' => false, 'translations' => [], 'error' => "HTTP {$httpCode}: {$apiMessage}", 'http_code' => $httpCode];
    }

    if (!isset($decoded['translations']) || !is_array($decoded['translations'])) {
        return ['success' => false, 'translations' => [], 'error' => 'Unerwartete Antwort: ' . substr($response, 0, 200), 'http_code' => $httpCode];
    }

    return [
        'success'      => true,
        'translations' => array_map(static fn($t) => $t['text'], $decoded['translations']),
        'error'        => '',
        'http_code'    => $httpCode,
    ];
}

