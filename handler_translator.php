if ($action === 'translator' && $_SERVER['REQUEST_METHOD'] === 'POST') {
    requireLogin();
    requireCsrf();

    $subAction = $_POST['translator_action'] ?? '';

    switch ($subAction) {

        // ── Sprachdateien speichern ──────────────────────────────────────
        case 'save': {
            $fileKey    = $_POST['file_key'] ?? '';
            $srcLang    = $_POST['src_lang'] ?? 'de';
            $tgtLang    = $_POST['tgt_lang'] ?? 'en';
            $newLangCode = trim($_POST['new_lang_code'] ?? '');

            // Neue Sprache anlegen?
            if ($tgtLang === '__new__' && $newLangCode !== '') {
                if (!translatorValidLangCode($newLangCode)) {
                    flash(t('tr_error_invalid_lang_code'), 'error');
                    redirect('?action=translator&file=' . urlencode($fileKey));
                }
                $tgtLang = $newLangCode;
            }

            $groups = translatorScanLangFiles();

            if (!isset($groups[$fileKey])) {
                flash(t('tr_error_invalid_file'), 'error');
                redirect('?action=translator');
            }

            $group     = $groups[$fileKey];
            $rawKeys   = $_POST['keys'] ?? [];
            $srcValues = $_POST['src_values'] ?? [];
            $tgtValues = $_POST['tgt_values'] ?? [];

            // SICHERHEITSNETZ (Verteidigung in der Tiefe, siehe Bugfix in
            // view_translator.php zum eigentlichen Auslöser): Quell- und
            // Zielsprache dürfen NIEMALS identisch sein - sonst schreiben die
            // beiden folgenden translatorSaveLangFile()-Aufrufe zweimal
            // hintereinander in DIESELBE Datei, wobei der zweite Aufruf
            // (mit den "Ziel"-Werten) die soeben geschriebenen "Quell"-Werte
            // überschreibt. Greift unabhängig davon, WARUM src_lang/tgt_lang
            // gleich sein könnten (der konkret behobene Auslöser war ein
            // JavaScript-Bug, aber diese Prüfung schützt auch vor jedem
            // anderen, noch unbekannten Weg zu diesem Zustand).
            if ($srcLang === $tgtLang) {
                flash(t('tr_error_same_language'), 'error');
                redirect('?action=translator&file=' . urlencode($fileKey)
                    . '&src=' . urlencode($srcLang) . '&tgt=' . urlencode($tgtLang));
            }

            $srcPath = translatorLangFilePath($group['dir'], $srcLang);
            $tgtPath = translatorLangFilePath($group['dir'], $tgtLang);
            if ($srcPath === null || $tgtPath === null) {
                flash(t('tr_error_invalid_lang_code'), 'error');
                redirect('?action=translator&file=' . urlencode($fileKey));
            }

            // Source-Array aufbauen
            $srcData = [];
            foreach ($rawKeys as $i => $key) {
                $key = (string)$key;
                if ($key === '') {
                    continue;
                }
                $srcData[$key] = trim($srcValues[$i] ?? '');
            }

            // Target-Array aufbauen
            $tgtData = [];
            foreach ($rawKeys as $i => $key) {
                $key = (string)$key;
                if ($key === '') {
                    continue;
                }
                $tgtData[$key] = trim($tgtValues[$i] ?? '');
            }

            // Dateien schreiben
            $srcOk = translatorSaveLangFile($srcPath, $srcData);
            $tgtOk = translatorSaveLangFile($tgtPath, $tgtData);

            if (!$srcOk || !$tgtOk) {
                flash(t('tr_error_data_loss_prevented'), 'error');
                redirect('?action=translator&file=' . urlencode($fileKey)
                    . '&src=' . urlencode($srcLang) . '&tgt=' . urlencode($tgtLang));
            }

            flash(t('tr_saved_success'));
            redirect('?action=translator&file=' . urlencode($fileKey)
                . '&src=' . urlencode($srcLang) . '&tgt=' . urlencode($tgtLang));
            break;
        }

        // ── Auto-Übersetzung fehlender Keys ───────────────────────────────
        case 'auto_translate': {
            $fileKey = $_POST['file_key'] ?? '';
            $srcLang = $_POST['src_lang'] ?? 'de';
            $tgtLang = $_POST['tgt_lang'] ?? 'en';
            $newLangCode = trim($_POST['new_lang_code'] ?? '');

            if ($tgtLang === '__new__' && $newLangCode !== '') {
                if (!translatorValidLangCode($newLangCode)) {
                    flash(t('tr_error_invalid_lang_code'), 'error');
                    redirect('?action=translator&file=' . urlencode($fileKey));
                }
                $tgtLang = $newLangCode;
            }

            $groups = translatorScanLangFiles();

            if (!isset($groups[$fileKey])) {
                flash(t('tr_error_invalid_file'), 'error');
                redirect('?action=translator');
            }

            $config = translatorGetConfig();
            $apiKey = $config['deepl_key'] ?? '';

            if ($apiKey === '') {
                flash(t('tr_error_no_api_key'), 'error');
                redirect('?action=translator&file=' . urlencode($fileKey)
                    . '&src=' . urlencode($srcLang) . '&tgt=' . urlencode($tgtLang));
            }

            $group   = $groups[$fileKey];

            // Gleiches Sicherheitsnetz wie bei 'save' oben.
            if ($srcLang === $tgtLang) {
                flash(t('tr_error_same_language'), 'error');
                redirect('?action=translator&file=' . urlencode($fileKey)
                    . '&src=' . urlencode($srcLang) . '&tgt=' . urlencode($tgtLang));
            }

            $srcPath = translatorLangFilePath($group['dir'], $srcLang);
            $tgtPath = translatorLangFilePath($group['dir'], $tgtLang);
            if ($srcPath === null || $tgtPath === null) {
                flash(t('tr_error_invalid_lang_code'), 'error');
                redirect('?action=translator&file=' . urlencode($fileKey));
            }

            $srcData = translatorLoadLangFile($srcPath);
            $tgtData = translatorLoadLangFile($tgtPath);

            // Fehlende Übersetzungen sammeln
            $missing     = [];
            $missingKeys = [];
            foreach ($srcData as $key => $value) {
                if (!isset($tgtData[$key]) || $tgtData[$key] === '') {
                    $missing[]     = $value;
                    $missingKeys[] = $key;
                }
            }

            if (empty($missing)) {
                flash(t('tr_nothing_to_translate'));
                redirect('?action=translator&file=' . urlencode($fileKey)
                    . '&src=' . urlencode($srcLang) . '&tgt=' . urlencode($tgtLang));
            }

            // DeepL API aufrufen (Batches von max. 50 Texten)
            $allTranslations = [];
            $batches = array_chunk($missing, 50);
            foreach ($batches as $batch) {
                $result = translatorDeepLTranslate($batch, $srcLang, $tgtLang, $apiKey);
                if (!$result['success']) {
                    // Konkreten Fehlergrund anzeigen statt einer generischen
                    // Meldung, siehe Docblock von translatorDeepLTranslate()
                    // für den Hintergrund.
                    flash(t('tr_error_translate_failed_detail', ['error' => $result['error']]), 'error');
                    redirect('?action=translator&file=' . urlencode($fileKey)
                        . '&src=' . urlencode($srcLang) . '&tgt=' . urlencode($tgtLang));
                }
                $allTranslations = array_merge($allTranslations, $result['translations']);
            }

            // Übersetzungen eintragen
            foreach ($missingKeys as $i => $key) {
                $tgtData[$key] = $allTranslations[$i] ?? '';
            }

            $saveOk = translatorSaveLangFile($tgtPath, $tgtData);
            if (!$saveOk) {
                flash(t('tr_error_data_loss_prevented'), 'error');
                redirect('?action=translator&file=' . urlencode($fileKey)
                    . '&src=' . urlencode($srcLang) . '&tgt=' . urlencode($tgtLang));
            }

            flash(t('tr_auto_translated', ['n' => count($missing)]));
            redirect('?action=translator&file=' . urlencode($fileKey)
                . '&src=' . urlencode($srcLang) . '&tgt=' . urlencode($tgtLang));
            break;
        }

        // ── DeepL API-Key speichern ───────────────────────────────────────
        case 'save_config': {
            $config = translatorGetConfig();
            $config['deepl_key'] = trim($_POST['deepl_key'] ?? '');
            translatorSaveConfig($config);
            flash(t('tr_config_saved'));
            redirect('?action=translator&file=' . urlencode($_POST['file_key'] ?? '')
                . '&src=' . urlencode($_POST['src_lang'] ?? 'de')
                . '&tgt=' . urlencode($_POST['tgt_lang'] ?? 'en'));
            break;
        }
    }
